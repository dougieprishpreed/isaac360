"""Generates src/recomp/gl_passthrough.inc from Khronos' gl.xml (tools/recomp/third_party/gl.xml).

One stdcall thunk per GL command: reads the arguments from the guest stack (GLdouble/GLint64/GLuint64 take 8
bytes, the rest 4), turns guest pointers into host pointers, calls the host driver's function and returns the
result in eax (or st0 for a float/double result). Used by the Windows build to run the recompiled game on the
real OpenGL driver while the console's GL-on-Vulkan layer is written (docs/RECOMP_PLAN.md).

Pointer parameters that can be buffer offsets (a buffer bound to the matching target) are passed through as
offsets when such a buffer is bound: see OFFSET_PARAMS.

    tools/.venv/Scripts/python tools/recomp/gen_gl.py
"""
import os
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
XML = os.path.join(ROOT, 'tools', 'recomp', 'third_party', 'gl.xml')
OUT = os.path.join(ROOT, 'src', 'recomp', 'gl_passthrough.inc')

WIDE = {'GLdouble', 'GLclampd', 'GLint64', 'GLuint64', 'GLint64EXT', 'GLuint64EXT'}
# (command, parameter) -> the buffer binding that turns the pointer into an offset
OFFSET_PARAMS = {
    ('glVertexAttribPointer', 'pointer'): 0x8894, ('glVertexAttribIPointer', 'pointer'): 0x8894,
    ('glVertexAttribPointerARB', 'pointer'): 0x8894, ('glVertexPointer', 'pointer'): 0x8894,
    ('glColorPointer', 'pointer'): 0x8894, ('glTexCoordPointer', 'pointer'): 0x8894,
    ('glNormalPointer', 'pointer'): 0x8894,
    ('glDrawElements', 'indices'): 0x8895, ('glDrawRangeElements', 'indices'): 0x8895,
    ('glDrawElementsBaseVertex', 'indices'): 0x8895, ('glDrawElementsInstanced', 'indices'): 0x8895,
    ('glTexImage2D', 'pixels'): 0x88EF, ('glTexSubImage2D', 'pixels'): 0x88EF,
    ('glCompressedTexImage2D', 'data'): 0x88EF, ('glCompressedTexSubImage2D', 'data'): 0x88EF,
    ('glReadPixels', 'pixels'): 0x88ED, ('glGetTexImage', 'pixels'): 0x88ED,
}
# a null data pointer stays null (glBufferData with no initial data, etc.)


def ctype(param):
    t = (param.text or '')
    ptype = param.find('ptype')
    if ptype is not None:
        t += ptype.text + (ptype.tail or '')
    return t.strip()


def main():
    root = ET.parse(XML).getroot()
    cmds = []
    for cmd in root.find('commands'):
        proto = cmd.find('proto')
        name = proto.find('name').text
        ret = ''.join(proto.itertext()).replace(name, '').strip()
        params = []
        for p in cmd.findall('param'):
            pname = p.find('name').text
            t = ctype(p)
            params.append((t, pname))
        cmds.append((name, ret, params))
    lines = ['// Generated by tools/recomp/gen_gl.py from gl.xml: do not edit.',
             '// GL_PT(name, ret_kind, arg_bytes, body) for every GL command.']
    for name, ret, params in cmds:
        if not name.startswith('gl') or name.startswith('glX'):
            continue
        off = 0
        decl = []
        call = []
        ok = True
        for t, pname in params:
            if '*' in t or t in ('GLsync', 'GLDEBUGPROC', 'GLDEBUGPROCARB', 'GLDEBUGPROCKHR', 'GLDEBUGPROCAMD',
                                 'GLVULKANPROCNV', 'GLeglImageOES', 'GLeglClientBufferEXT'):
                key = (name, pname)
                if key in OFFSET_PARAMS:
                    decl.append('void* a%d = gl_ptr_or_offset(ARG(c, %d), 0x%x);' % (len(call), off // 4, OFFSET_PARAMS[key]))
                elif t in ('GLsync',):
                    decl.append('void* a%d = gl_sync_handle(ARG(c, %d));' % (len(call), off // 4))
                elif t.startswith('GLDEBUGPROC') or t in ('GLVULKANPROCNV',):
                    decl.append('void* a%d = 0;' % len(call))
                else:
                    decl.append('void* a%d = gl_ptr(ARG(c, %d));' % (len(call), off // 4))
                call.append('(%s)a%d' % (t, len(call)))
                off += 4
            elif t in WIDE:
                decl.append('uint64_t a%d = (uint64_t)ARG(c, %d) | ((uint64_t)ARG(c, %d) << 32);' % (len(call), off // 4, off // 4 + 1))
                if t in ('GLdouble', 'GLclampd'):
                    call.append('Q2D(a%d)' % len(call))
                else:
                    call.append('(%s)a%d' % (t, len(call)))
                off += 8
            elif t in ('GLfloat', 'GLclampf'):
                decl.append('float a%d = ARGF(c, %d);' % (len(call), off // 4))
                call.append('a%d' % len(call))
                off += 4
            elif t in ('GLsizeiptr', 'GLintptr', 'GLsizeiptrARB', 'GLintptrARB'):
                decl.append('intptr_t a%d = (int32_t)ARG(c, %d);' % (len(call), off // 4))
                call.append('(%s)a%d' % (t, len(call)))
                off += 4
            elif t.startswith('GL') or t in ('const GLenum',):
                decl.append('uint32_t a%d = ARG(c, %d);' % (len(call), off // 4))
                call.append('(%s)a%d' % (t.replace('const ', ''), len(call)))
                off += 4
            else:
                ok = False
                break
        if not ok:
            continue
        nargs = off // 4
        protot = '%s (APIENTRY *)(%s)' % (ret or 'void', ', '.join(t for t, _ in params) or 'void')
        fn = '((%s)gl_host("%s"))' % (protot, name)
        callexpr = '%s(%s)' % (fn, ', '.join(call))
        if ret in ('void', ''):
            body = '%s %s; RET_STD(c, %d, 0);' % (' '.join(decl), callexpr, nargs)
        elif ret in ('GLfloat', 'GLdouble'):
            body = '%s double r_ = %s; X87_PUSH(c, r_); c->r[4] += 4 + %d;' % (' '.join(decl), callexpr, 4 * nargs)
        elif '*' in ret or ret in ('GLsync',):
            body = '%s const void* r_ = (const void*)%s; RET_STD(c, %d, gl_guest_ptr(r_, "%s"));' % (' '.join(decl), callexpr, nargs, name)
        elif ret in ('GLuint64', 'GLint64'):
            body = '%s uint64_t r_ = (uint64_t)%s; c->r[2] = (uint32_t)(r_ >> 32); RET_STD(c, %d, (uint32_t)r_);' % (' '.join(decl), callexpr, nargs)
        else:
            body = '%s uint32_t r_ = (uint32_t)%s; RET_STD(c, %d, r_);' % (' '.join(decl), callexpr, nargs)
        lines.append('GL_PT(%s, { %s })' % (name, body))
    with open(OUT, 'w', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    # the types the commands use, from the registry's <types> (khrplatform's are defined by the includer)
    tl = ['// Generated by tools/recomp/gen_gl.py from gl.xml: do not edit.']
    for t in root.find('types'):
        if t.get('api') not in (None, 'gl'):
            continue
        text = ''.join(t.itertext()).strip()
        if not text or text.startswith('#include') or 'khrplatform' in text:
            continue
        tl.append(text)
    with open(os.path.join(ROOT, 'src', 'recomp', 'gl_types.inc'), 'w', newline='\n') as f:
        f.write('\n'.join(tl) + '\n')
    print('wrote %d commands' % (len(lines) - 2))


if __name__ == '__main__':
    main()
