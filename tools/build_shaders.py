"""Compiles src/render/shaders/*.vert|*.frag to SPIR-V and writes src/render/shaders/spirv.inc.

The Windows binary and the console build embed the same SPIR-V words, so the console's shader bundle
(vulkan4xenon's tools/build_shaders.py, docs/XSDK_PLAN.md) matches them by hash. Run it after
changing a shader and commit spirv.inc with the change.

The compiler is glslang-xenon's host build in the WSL distro CTR360-XSDK (GLSLANG names another glslang;
a Windows path runs directly, anything else runs in WSL).

    py -3 tools/build_shaders.py
"""
import os
import struct
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHADERS = os.path.join(ROOT, 'src', 'render', 'shaders')
OUT = os.path.join(SHADERS, 'spirv.inc')
GLSLANG = os.environ.get('GLSLANG', '/opt/ctr360-xsdk/glslang/build-host/StandAlone/glslang')
DISTRO = os.environ.get('BOI360_WSL_DISTRO', 'CTR360-XSDK')


def wsl_path(p):
    p = os.path.abspath(p).replace('\\', '/')
    return '/mnt/' + p[0].lower() + p[2:]


def compile_one(src, dst):
    if os.path.isabs(GLSLANG) and os.path.exists(GLSLANG):
        cmd = [GLSLANG, '-V', '-o', dst, src]
    else:
        cmd = ['wsl.exe', '-d', DISTRO, '--', GLSLANG, '-V', '-o', wsl_path(dst), wsl_path(src)]
    env = dict(os.environ, MSYS_NO_PATHCONV='1')
    r = subprocess.run(cmd, capture_output=True, text=True, env=env)
    if r.returncode != 0:
        sys.stderr.write(r.stdout + r.stderr)
        raise SystemExit('glslang failed on ' + os.path.basename(src))


def main():
    names = sorted(f for f in os.listdir(SHADERS) if f.endswith(('.vert', '.frag')))
    out = ['// Generated by tools/build_shaders.py from src/render/shaders: do not edit.',
           '// SPIR-V words, one array a shader (name_vert / name_frag).']
    with tempfile.TemporaryDirectory(dir=os.path.join(ROOT, 'build') if os.path.isdir(os.path.join(ROOT, 'build')) else None) as tmp:
        for name in names:
            spv = os.path.join(tmp, name + '.spv')
            compile_one(os.path.join(SHADERS, name), spv)
            data = open(spv, 'rb').read()
            words = struct.unpack('<%dI' % (len(data) // 4), data)
            ident = name.replace('.', '_')
            out.append('static const u32 SPV_%s[%d] = {' % (ident, len(words)))
            for i in range(0, len(words), 8):
                out.append('    ' + ', '.join('0x%08x' % w for w in words[i:i + 8]) + ',')
            out.append('};')
            print('%-22s %5d words' % (name, len(words)))
    open(OUT, 'wb').write(('\n'.join(out) + '\n').encode('ascii'))
    print('wrote', os.path.relpath(OUT, ROOT))


if __name__ == '__main__':
    main()
